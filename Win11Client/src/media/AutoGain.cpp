#include "AutoGain.h"
#include <QtMath>

// Всё в долях полной шкалы (0..1), кадр — 20 мс.
namespace {

// Куда ведём ОГИБАЮЩУЮ речи (не громкость кадра — см. AutoGain::m_env).
// Огибающая идёт по громким слогам, поэтому долговременный уровень выходит
// ниже: на речеподобном сигнале замерено −23 dBov, то есть порядок активного
// уровня речи по ITU-T P.56 (там для телефонии называют −26). Выше начинаешь
// драться с пиками — между слогом и его пиком легко 10 дБ; ниже — заставляешь
// собеседников крутить громкость. Если когда-нибудь покажется громко или
// тихо, крутить надо ровно это число и только его.
const qreal kTarget = 0.1;          // −20 dBFS по огибающей

// Спад огибающей: −0.15 дБ на кадр, то есть −7.5 дБ за секунду речи. Пауза
// между словами её почти не роняет (за 300 мс — 2 дБ), а на человека, который
// стал говорить тише, она сползает за пару секунд.
const qreal kEnvDecay = 0.9829;

// Насколько кадр должен превышать шумовую полку, чтобы считаться голосом.
// Одного «речь» от VAD мало: он для подсветки, и держит фразу сквозь паузы
// внутри неё. Огибающей же нужны кадры, в которых действительно есть голос, —
// иначе долгая «речь» без единого громкого кадра утащит её вниз, а за ней
// вверх уедет усиление.
const qreal kOverFloor = 4.0;       // +12 дБ над полкой

// Потолок пиков. Не единица: сжатый и разжатый Opus не обязан попасть в
// исходный сэмпл байт в байт, и запас в децибел — плата за то, чтобы
// округление не выходило за шкалу уже у собеседника.
const qreal kCeil = 0.89;           // −1 dBFS

// Пределы медленной части. +24 дБ хватает, чтобы вытянуть человека, отсевшего
// от микрофона на метр (это около −14 дБ), с запасом; дальше усиливаешь уже
// не человека, а комнату. Вниз −20 дБ: «горячее» устройство надо уметь
// прижать, иначе автоусиление работает только в одну сторону.
const qreal kMaxGain = 16.0;        // +24 dB
const qreal kMinGain = 0.1;         // −20 dB

// Абсолютный низ: тише этого кадр не голос ни при какой полке.
const qreal kQuiet = 0.002;         // −54 dBFS

// Куда разрешено вытянуть шумовую полку. −48 dBFS — уровень, на котором фон
// перестаёт замечаться на фоне речи.
const qreal kNoiseCeil = 0.004;     // −48 dBFS

// Скорости. Коэффициенты вида 1 − exp(−T/τ) при T = 20 мс.
const qreal kUp = 0.010;            // τ ≈ 2 с — подъём
const qreal kDown = 0.095;          // τ ≈ 0.2 с — спуск
const qreal kLimRelease = 0.18;     // τ ≈ 0.1 с — отпускание лимитера

// Окно шумовой полки: 150 кадров, а с учётом второго слота минимум берётся за
// 3–6 с. Такой длины хватает, чтобы внутрь заведомо попало несколько пауз
// между словами, — иначе речь без единого вдоха подняла бы полку сама и
// задавила бы усиление у тихого человека.
const int kNoiseWindow = 150;

// Первое окно короче: до него полки не существует вовсе, а значит не работают
// оба ограничения ниже. Секунда — компромисс между «начать защищать пораньше»
// и «не принять начало фразы за фон».
const int kNoiseWarmup = 50;

} // namespace

AutoGain::AutoGain(qreal startGain)
    : m_log(qLn(qBound(kMinGain, startGain, kMaxGain))),
      m_slow(qBound(kMinGain, startGain, kMaxGain)),
      m_applied(m_slow) {}

void AutoGain::process(qint16* samples, int count, qreal rms, qreal peak, bool speech) {
    if (count <= 0) return;

    // ---- шумовая полка ----
    // Меряется по ВСЕМ кадрам, а не только по паузам, и это принципиально.
    // Речь прерывиста — минимум за окно всё равно попадает на паузу между
    // словами, — зато измерение не зависит от детектора речи. А зависеть от
    // него нельзя: полка нужна ровно там, где детектор ошибается.
    //
    // Прошлая версия обновляла полку только там, где «речи нет», и переставала
    // существовать в том самом случае, ради которого написана: шумодав был
    // выключен, за окном улица, SpeechGate принимал её за речь — пауз в его
    // понимании не бывало вовсе, полка оставалась неизмеренной, оба
    // ограничения ниже отключались, и усиление уезжало к потолку, вытягивая
    // улицу (замечено вживую на 1500 %).
    //
    // Ту конфигурацию настройки с тех пор не допускают вовсе — автоусиление
    // требует шумоподавления, — но здесь ничего не упростилось: RNNoise тоже
    // ошибается, просто реже. Это та же ошибка, что была в первой версии
    // SpeechGate (см. её комментарий): «обновлять только когда детектор
    // говорит X» ломается ровно тогда, когда детектор говорит X ошибочно.
    if (rms < m_nCur) m_nCur = rms;
    if (++m_nCount >= (m_nPrev < 1.0 ? kNoiseWindow : kNoiseWarmup)) {
        m_nPrev = m_nCur; m_nCur = rms; m_nCount = 0;
    }
    // Полка считается известной только после того, как закрылось первое окно.
    // Минимум по трём кадрам — это не фон, а просто самый тихий из трёх, и
    // если захват начался сразу с речи, он равен уровню речи: ограничения
    // сработали бы против того самого голоса, который надо усилить.
    const bool floorKnown = m_nPrev < 1.0;
    const qreal noise = qMin(m_nCur, m_nPrev);
    // Потолок не опускается ниже единицы: шумная комната — это повод не
    // усиливать, но не повод делать человека тише, чем он есть.
    const qreal top = floorKnown
        ? qMin(kMaxGain, qMax(qreal(1.0), kNoiseCeil / qMax(noise, qreal(1e-9))))
        : kMaxGain;

    // ---- медленная часть ----
    // Считаем в логарифме, а не в разах: одна и та же прибавка к ln — это одно
    // и то же число децибел, на каком бы усилении мы ни находились. В линейной
    // шкале тот же коэффициент означал бы, что с 8× гейн ползёт в восемь раз
    // быстрее, чем с единицы, — и на слух это два разных автоусиления.
    const qreal voiced = floorKnown ? qMax(kQuiet, noise * kOverFloor) : kQuiet;
    if (speech && rms > voiced) {
        m_env = qMax(rms, m_env * kEnvDecay);
        // Пока полки нет, огибающую копим, а усиление держим на том, с чего
        // стартовали. Эта секунда — единственное время, когда оба ограничения
        // выключены, и отпускать в неё усиление незачем: тихий шум в комнате
        // неотличим от очень тихого человека, и AGC успел бы разогнать его в
        // пару раз, прежде чем полка появится и заберёт это обратно.
        if (floorKnown) {
            const qreal want = qBound(kMinGain, kTarget / m_env, top);
            const qreal k = qLn(want) < m_log ? kDown : kUp;
            m_log += (qLn(want) - m_log) * k;
        }
    }
    // Потолок мог опуститься, пока мы молчали (заработал кондиционер), — тогда
    // прижимаем и без речи: иначе на следующей фразе фон уже вытянут.
    m_log = qBound(qLn(kMinGain), m_log, qLn(top));
    const qreal slow = qExp(m_log);
    m_slow = slow;

    // ---- лимитер ----
    // Наибольший множитель, при котором пик ЭТОГО кадра ещё влезает в шкалу.
    const qreal safe = peak > 0 ? kCeil / peak : kMaxGain;
    // Вниз — сразу, вверх — плавно. Мгновенный возврат превратил бы лимитер в
    // источник «дыхания»: на каждом громком слоге звук проваливался бы и
    // выскакивал обратно.
    const qreal target = qMin(safe / slow, qreal(1.0));
    m_lim = target < m_lim ? target : m_lim + (target - m_lim) * kLimRelease;

    // ---- применение ----
    // Множитель меняется не ступенькой на границе кадра, а линейно внутри него:
    // ступенька в 50 раз в секунду слышна как призвук. Оба конца отрезка не
    // выше safe — значит и всё, что между ними, тоже, и до жёсткого среза дело
    // не доходит вовсе (qBound ниже остаётся страховкой, а не механизмом).
    const qreal gEnd = slow * m_lim;
    const qreal gStart = qMin(m_applied, safe);
    const qreal step = (gEnd - gStart) / count;
    for (int i = 0; i < count; ++i) {
        const qreal g = gStart + step * i;
        samples[i] = qint16(qBound<qint32>(-32768, qint32(samples[i] * g), 32767));
    }
    m_applied = gEnd;
}
