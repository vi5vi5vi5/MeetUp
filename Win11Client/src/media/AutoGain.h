#pragma once
#include <QtGlobal>

// Автоусиление микрофона: собеседники слышат вас одинаково громко независимо
// от того, придвинулись вы к микрофону или отсели, и независимо от того,
// насколько «горячее» само устройство.
//
// Ползунок чувствительности решает ту же задачу, но один раз и вручную: он
// верен ровно для той посадки, при которой его выставили. Здесь множитель
// пересчитывается каждый кадр — поэтому, когда автоусиление включено, ползунок
// перестаёт быть органом управления и становится индикатором: показывает то,
// что выставил этот класс.
//
// Три части, и все три обязательны:
//
//  * Медленная часть ведёт уровень речи к цели. Уровень — это ОГИБАЮЩАЯ, а не
//    громкость очередного кадра; почему именно так, написано у m_env, и это
//    самое важное место класса. Скорости разные в две стороны: вверх — секунды
//    (спешка слышна как наплыв фона между фразами), вниз — доли секунды
//    (промедление слышно как хруст перегрузки).
//  * Лимитер держит ПИК. Усиление, поднятое ради тихого голоса, превращает
//    внезапный смех в переполнение Int16, а это уже ничем не лечится. Пик
//    кадра известен до того, как кадр усилен, — то есть у лимитера есть 20 мс
//    упреждения, и достаются они даром: кадр всё равно лежит в буфере целиком.
//  * Потолок по шумовой полке не даёт вытянуть тихую комнату до состояния
//    «слышно каждую муху». Усиление ограничивается так, чтобы фон остался
//    ниже слышимого, — но никогда не ниже единицы: отказать в усилении можно,
//    заглушать человека из-за шумной комнаты нельзя.
//
// Считает только громкость. Что именно считать речью, класс не решает — это
// приходит снаружи; в конференции ответ даёт RNNoise, но подошёл бы и любой
// другой. Без такого разделения автоусиление разгоняет паузы: сигнала нет,
// «слишком тихо», и через пару секунд собеседники слушают ваш холодильник в
// полный рост. И наоборот — доверять этому ответу безоглядно тоже нельзя,
// см. шумовую полку в .cpp: детектор ошибается, и защита нужна именно тогда.
class AutoGain {
public:
    // startGain — с чего начать (ползунок чувствительности на момент
    // включения): переход между ручным и автоматическим режимом не должен
    // быть слышен скачком.
    explicit AutoGain(qreal startGain = 1.0);

    // Кадр 20 мс, Int16, уже прошедший шумоподавление. rms и peak — доли полной
    // шкалы (0..1) по этому же кадру, посчитанные ДО усиления. Усиление
    // применяется на месте.
    void process(qint16* samples, int count, qreal rms, qreal peak, bool speech);

    // Для ползунка в настройках — только медленная часть, без лимитера.
    // Лимитер живёт миллисекундами и дёргается на каждом громком слоге; ручка,
    // повторяющая его, показывала бы дрожь вместо чувствительности.
    qreal gain() const { return m_slow; }

private:
    // Уровень речи: недавний максимум с медленным спадом.
    //
    // Так стало не сразу, и на этом класс первый раз сломался целиком.
    // Сначала усиление вела громкость очередного кадра, и на живом голосе оно
    // за двадцать секунд уезжало до +17 дБ. Причина в том, что внутри фразы
    // тихих кадров БОЛЬШЕ, чем громких: хвосты слов, придыхания, паузы между
    // словами — а речью их держит тот же VAD (нижний порог специально не даёт
    // подсветке мигать на каждом вдохе). Каждый такой кадр честно сообщает
    // «не хватает двадцати децибел», и хотя спуск в девять раз быстрее
    // подъёма, тихих кадров хватает, чтобы равновесие уползло к потолку.
    //
    // Максимум за последние доли секунды такого свойства не имеет: он
    // отвечает на вопрос «насколько громко человек говорит», а не «насколько
    // громок этот конкретный двадцатимиллисекундный кусок».
    qreal m_env = 0;
    qreal m_log;             // медленная часть, в ln (там дБ линейны, см. .cpp)
    qreal m_slow;            // она же в разах — снимок для gain()
    qreal m_applied;         // с лимитером; отсюда стартует следующий кадр
    qreal m_lim = 1.0;       // множитель лимитера, всегда <= 1
    // Шумовая полка: минимум по паузам за окно. Именно минимум и именно за
    // окно — по той же причине, что в SpeechGate: сглаживание, которому
    // запрещено расти во время речи, залипает навсегда.
    qreal m_nCur = 1e9, m_nPrev = 1e9;
    int m_nCount = 0;
};
