#include <QtGlobal>
#include <QByteArray>
#include <QVector>
#include <vector>

struct SpeexEchoState_;
struct SpeexPreprocessState_;

// Эхоподавитель микрофона поверх SpeexDSP (третья сторона, порт vcpkg).
//
// Задача не та, что у шумодава: убрать из микрофона не шум комнаты, а СВОЙ ЖЕ
// звук — голоса собеседников, которые вышли из колонок и вернулись в микрофон.
// Для этого нужен второй, опорный сигнал: что именно ушло в динамики. У нас он
// есть даром — кадр микса, который AudioWorker::pump() пишет в звуковую карту;
// захват и вывод живут на одном потоке, и никакой синхронизации между ними
// не нужно.
//
// Внутри — адаптивный фильтр MDF (блочный, в частотной области): он подбирает
// импульсный отклик пути «динамик → комната → микрофон» и вычитает свёртку
// опорного сигнала с ним. Хвост фильтра — сколько задержки он готов покрыть;
// путь у нас длинный: ~60 мс лежит в синке, ещё десятки — в драйверах вывода и
// захвата, поэтому хвост 400 мс, с запасом.
//
// Выравнивание. Сыгранные сэмплы копятся в очереди, каждый кадр микрофона
// читает из неё 960: опорный поток непрерывен и в точности равен сыгранному —
// это главное, что нужно адаптивному фильтру. n-й кадр микрофона встречает n-й
// записанный в синк кадр, и найденная фильтром задержка равна настоящему пути
// «синк → колонки → микрофон» (100..250 мс, внутри хвоста). Запас очереди
// после чтения держим около двух кадров — под всплески планировщика (насос
// кладёт до трёх кадров разом, захват приносит их пачками).
//
// Дальше — два РАЗНЫХ по природе расхождения, и лечатся они по-разному. Путать
// их нельзя: именно на этом первая версия и сломалась.
//
//  * РАЗОВОЕ СМЕЩЕНИЕ уровня: насос на секунду встал (модальный цикл окна,
//    загрузка), захват в это время вычерпывал очередь. Само по себе оно
//    безвредно — это просто лишние десятки миллисекунд задержки эха внутри
//    хвоста. Чинится РАЗОВО и дискретно: подвинуть курсор чтения (или вставить
//    тишину, если очередь укоротилась). Фильтр переучится за секунду. Тянуть
//    смещение ресемплером НЕЛЬЗЯ: пока он тянет, опорный сигнал плывёт по
//    времени — то есть мы сами создаём ровно тот дрейф, от которого лечимся.
//    Проверено синтетикой: 20 дБ превращались в 4.
//
//  * ДРЕЙФ ЧАСОВ: микрофон и динамики на разных устройствах (USB-микрофон,
//    вебкамера, Bluetooth) тикают каждое по-своему, и частоты расходятся на
//    десятки-сотни миллионных долей. Для фильтра это смертельно: 50 ppm — это
//    2,4 сэмпла в секунду, и через несколько секунд отклик перестаёт совпадать
//    с эхом по фазе на всех частотах выше пары килогерц (синтетика: 20 дБ ->
//    5 дБ). Speex этого не лечит вовсе — его документация прямо требует общий
//    клок. Лечим сами: опорный поток читается не по целым сэмплам, а по дробной
//    позиции с шагом (1 + поправка), а поправку ведёт медленная ПИ-петля по
//    уровню очереди. Уровень — идеальный измеритель: он уходит ровно на столько
//    сэмплов, на сколько вывод обогнал захват, и виден даже когда динамики
//    молчат. Дискретные починки выше держат ошибку петли маленькой, поэтому её
//    поправка всегда мала, а накопленная (интеграл) и есть найденный дрейф — он
//    показывается в «Диагностике» (driftPpm).
//
//    Мерить дрейф по длине СВОЕЙ очереди нельзя, и это стоило отдельного круга
//    отладки: насос кладёт в неё целые кадры по 960 сэмплов, поэтому её длина —
//    лестница со ступенькой в 20 мс, а дрейф в полсотни ppm сдвигает эту
//    лестницу на одну ступеньку за много минут. Петля при этом либо не видит
//    ничего, либо реагирует на ступеньку рывком в тысячи ppm — то есть сама
//    рвёт выравнивание. Считать надо то, что звуковая карта РЕАЛЬНО проиграла:
//    записанное в синк минус то, что в нём ещё лежит (QAudioSink отдаёт остаток
//    с точностью до сэмпла). Это число растёт непрерывно и ровно с частотой
//    динамиков, поэтому расхождение с нашим чтением — прямая мера дрейфа, и
//    петля видит его за секунды, а не за минуты.
//
//    Интерполяция между сэмплами — кубическая (Катмулл-Ром, четыре отвода).
//    Линейной здесь мало: её ошибка на верхах доходит до −30 дБ и ползёт вместе
//    с дробной позицией, то есть ставит потолок ровно там, где мы работаем.
//    Ресемплер самого Speex не годится по другой причине: он строит таблицу
//    синка размером «длина фильтра × знаменатель», а знаменателя мельче
//    миллионной доли требует как раз дрейф — таблица выходит в гигабайты.
//
// Остаточное эхо. Линейный фильтр вычитает то, что колонки воспроизвели
// линейно; дешёвые динамики искажают, и остаток слышен. Его давит препроцессор
// Speex по спектру — там, где остаток есть, а речи нет. Шумоподавление у него
// сведено к нулю: шум — дело RNNoise, и два шумодава подряд портят голос.
//
// Живёт на потоке звука, вместе с захватом: состояние адаптивное, разрыв потока
// сэмплов — разрыв и для него.
class EchoCanceller {
public:
    EchoCanceller();
    ~EchoCanceller();
    EchoCanceller(const EchoCanceller&) = delete;
    EchoCanceller& operator=(const EchoCanceller&) = delete;

    bool ready() const { return m_echo != nullptr; }

    // Кадр (960 сэмплов Int16), только что записанный в звуковую карту, — то,
    // что услышит микрофон. Зовётся из насоса вывода на каждый кадр.
    // sinkQueuedSamples — сколько сэмплов лежит в синке НЕПРОИГРАННЫМИ сразу
    // после этой записи: по нему считается, что динамики успели сыграть на
    // самом деле (см. выше про дрейф). Отрицательное значение = «не знаю»,
    // тогда дрейф не ищем вовсе.
    void playback(const QByteArray& frame, int sinkQueuedSamples);
    // Кадр микрофона: вычесть эхо на месте. count обязан быть 960.
    void capture(qint16* samples, int count);
    // Сменились динамики: путь до эха другой, отклик фильтра — мусор. Очередь
    // при этом НЕ трогаем: она задаёт выравнивание, а его смена устройства не
    // меняет (см. выше про порядок кадров).
    void dropPlayback();

    // ---- показатели для «Диагностики» ----
    // Подавление: на сколько дБ кадр микрофона стал тише после вычитания,
    // усреднённое по кадрам, где динамики звучали. При одновременном разговоре
    // число честно проседает: вычитать можно только эхо, а не собеседника.
    qreal suppressionDb() const { return m_erleDb; }
    // Где фильтр нашёл эхо: положение пика импульсного отклика, мс. −1 — ещё
    // не сошёлся (отклик плоский). Главное число для отладки: у нуля — значит,
    // опорный сигнал подан слишком поздно и вычитать уже нечего.
    int echoDelayMs() const { return m_delayMs; }
    // Динамики звучали в последнем кадре (есть что вычитать).
    bool farActive() const { return m_farActive; }
    // Сколько раз пришлось чинить смещение очереди дискретно (заминки насоса).
    int resyncs() const { return m_resyncs; }
    // Найденный дрейф часов «вывод относительно захвата», миллионные доли:
    // положительный — динамики тикают быстрее микрофона. На общем клоке — 0.
    int driftPpm() const { return int(m_step * 1e6 - 1e6); }

private:
    void updateDelay();
    void updateDrift();

    SpeexEchoState_* m_echo = nullptr;
    SpeexPreprocessState_* m_pre = nullptr;
    // Опорный поток: сыгранные сэмплы. Читается по дробной позиции m_pos с
    // шагом m_step (см. выше про дрейф); хвост подрезается пачками.
    std::vector<qint16> m_ref;
    double m_pos = 0;               // курсор чтения, сэмплы от начала m_ref
    double m_step = 1.0;            // 1 + поправка на дрейф
    std::vector<qint16> m_play;     // опорный кадр под текущий кадр микрофона
    QByteArray m_out;
    QVector<qint32> m_impulse;      // буфер под импульсный отклик (диагностика)
    // Часы вывода и чтения — обе в сэмплах от начала захвата.
    qint64 m_written = 0;           // записано в синк
    qint64 m_played = -1;           // …из них РЕАЛЬНО прозвучало (−1 — неизвестно)
    qint64 m_playedPrev = -1;       // столько же секундой раньше (проверка меры)
    double m_consumed = 0;          // прочитано опорного потока (с учётом шага)
    // Петля дрейфа: держим постоянной разницу «прозвучало минус прочитано».
    // Само её значение (смещение) роли не играет — важно, чтобы оно не плыло.
    bool m_aligned = false;
    int m_warmup = 0;               // тиков, пока синк наполняется (см. .cpp)
    double m_target = 0;            // та самая разница на момент выравнивания
    double m_diffSum = 0;           // сумма её значений за текущую секунду…
    int m_diffCount = 0;            // …и сколько их было (нужно среднее)
    double m_diffEma = 0;           // среднее, сглаженное между секундами
    double m_integral = 0;          // накопленная поправка (сам дрейф)
    qreal m_erleDb = 0;
    int m_delayMs = -1;
    bool m_farActive = false;
    int m_resyncs = 0;
    int m_frames = 0;               // для прореживания диагностики
};
