#pragma once
#include <QtGlobal>
#include <QVector>

struct DenoiseState;

// Шумоподавление микрофона поверх RNNoise (третья сторона, см. CMakeLists).
// Гибрид: DSP раскладывает кадр по 22 полосам барк-шкалы, маленькая
// рекуррентная сеть предсказывает, сколько усиления оставить в каждой. Отсюда
// то, чего не умеет обычное спектральное вычитание, — нестационарный шум:
// клавиатура, стук, шаги, бормотание за стеной. Вентилятор и гул убирает
// заодно.
//
// Живёт на потоке звука (AudioWorker) и наружу оттуда не выходит: состояние
// рекуррентное, то есть один экземпляр — один непрерывный поток сэмплов, и
// делить его между потоками нельзя.
//
// Формат совпал с форматом конференции без единого преобразования: RNNoise
// написан ровно под 48 кГц моно и кадр 480 сэмплов — это в точности половина
// нашего двадцатимиллисекундного кадра.
class Denoiser {
public:
    Denoiser();
    ~Denoiser();
    Denoiser(const Denoiser&) = delete;
    Denoiser& operator=(const Denoiser&) = delete;

    // Модель поднялась. Ложь — RNNoise не смог выделить состояние; звать
    // process() всё равно можно, он просто вернёт сигнал нетронутым.
    bool ready() const { return m_st != nullptr; }

    // Подавить шум в кадре на месте. count обязан быть кратен frameSize();
    // остаток (которого при кадре 960 не бывает) остаётся как есть.
    //
    // Возвращает вероятность речи 0..1 — тот же вызов считает её попутно.
    // На кадре из нескольких блоков берётся наибольшая: кадр, в котором
    // человек начал говорить со второй половины, — это кадр с речью.
    float process(qint16* samples, int count);

    // Сколько сэмплов RNNoise съедает за раз (480 при 48 кГц).
    static int frameSize();

private:
    DenoiseState* m_st = nullptr;
    // Перегон Int16 <-> float. Живут полями, а не на стеке вызова: process()
    // зовётся сто раз в секунду, и незачем каждый раз трогать аллокатор.
    QVector<float> m_in, m_out;
};
