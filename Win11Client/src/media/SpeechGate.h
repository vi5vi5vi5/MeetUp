#pragma once
#include <QtGlobal>
#include <QtMath>

// «Говорит или молчит» по одной громкости — там, где вероятность речи взять
// негде: у собеседника (его звук приезжает уже кодированным, и гонять чужой
// голос через сеть RNNoise значило бы платить процентом ядра за каждого
// участника) и у себя, когда шумоподавление выключено.
//
// Считает НЕ абсолютный уровень, а превышение над шумовой полкой самого
// говорящего. Абсолютный порог здесь врёт всегда и в обе стороны: тихого
// человека с дальним микрофоном он не слышит вовсе, а рядом с шумной комнатой
// зажигается от вентилятора. Полка же у каждого своя, и вопрос «стало громче,
// чем здесь обычно» — единственный, на который громкость честно отвечает.
class SpeechGate {
public:
    // rms — 0..1 по кадру (20 мс). Возвращает «речь идёт».
    bool feed(qreal rms) {
        // Полка — самый тихий кадр за последние 4–8 секунд. Именно минимум, а
        // не среднее и не сглаживание: речь прерывиста, паузы в ней и есть
        // фон, тогда как среднее речь утащила бы за собой.
        //
        // Так было не сразу. Первым здесь стояло экспоненциальное сглаживание,
        // которое поднималось, только пока молчим, — защита от того, чтобы
        // длинная фраза не подтянула полку к себе. На проверке выяснилось, что
        // защита оборачивается вечным залипанием: стоит фону разом вырасти
        // (включился кондиционер), детектор говорит «речь», подъём полки
        // запрещён этим же «речь» — и он не выйдет из этого состояния никогда.
        // Минимум за окно такого состояния не имеет вовсе.
        if (rms < m_cur) m_cur = rms;
        if (++m_n >= kWindow) { m_prev = m_cur; m_cur = rms; m_n = 0; }

        // Ниже абсолютного пола полка не опускается: в цифровой тишине любой
        // шорох — это «превышение в разы», и подсветка мигала бы от нуля.
        const qreal floor = qMax(qMin(m_cur, m_prev), kSilence);

        // Два порога: одиночный мигает у самой границы на каждом вдохе между
        // словами. Верхний зажигает, нижний — только удерживает начатое.
        if (rms > floor * (m_on ? kHold : kOpen)) {
            m_on = true;
            m_hang = kHang;
        } else if (m_hang > 0) {
            --m_hang;              // пауза между словами — фраза продолжается
        } else {
            m_on = false;
        }
        return m_on;
    }

    // Собеседник замолчал по своему собственному признанию (Opus DTX).
    // Полку не трогаем — она про его комнату и остаётся верной.
    void reset() { m_on = false; m_hang = 0; }

private:
    // 2 с при кадре 20 мс. Полка отстаёт от РЕЗКО выросшего фона на два окна
    // (пока минимум прежней тишины не вытеснится из обоих) — то есть до 4 с
    // ложной подсветки, если рядом внезапно включился кондиционер. Окно короче
    // сделало бы отставание меньше, но речь без пауз длиной в окно начала бы
    // поднимать полку сама; на 2 с пауз между словами попадает заведомо
    // несколько.
    static constexpr int kWindow = 100;
    static constexpr int kHang = 10;            // 200 мс: пауза между словами
    static constexpr qreal kSilence = 0.0008;   // ≈ −62 dBFS
    static constexpr qreal kOpen = 2.5;         // ≈ +8 dB над полкой
    static constexpr qreal kHold = 1.5;         // ≈ +3.5 dB

    // Большое начальное значение, а не 0: минимум должен собраться из первых
    // же кадров, а не считать нулевую тишину настоящим фоном.
    qreal m_cur = 1e9, m_prev = 1e9;
    int m_n = 0;
    int m_hang = 0;
    bool m_on = false;
};
