#pragma once

#include <QString>
#include <QStringList>

#include "config/Log.h"

// Настройки сервера: файл `<data-dir>/meetup.conf` плюс переменные окружения.
//
// Зачем файл, а не только аргументы командной строки: аргументы в докере
// прибиты в CMD образа, и чтобы поменять лимит, пришлось бы править
// docker-compose.yml — то есть файл из репозитория, который затрёт следующий
// `git pull`. Конфиг лежит в `mount/` — это уже том, он переживает и
// пересборку образа, и обновление из гита.
//
// Зачем ещё и переменные окружения: тому, кто держит всё в compose, удобнее
// один раз написать `MEETUP_WEB_ENABLED=false` там, а не заходить внутрь тома.
// Окружение сильнее файла.
//
// Формат — INI: секции в квадратных скобках, `ключ = значение`, комментарии с
// `#` или `;`. Разбор свой, не QSettings, по двум причинам: QSettings считает
// значение с запятыми списком (имя сервера «Дача, второй этаж» превратилось бы
// в пустую строку) и умеет переписать файл, растеряв комментарии, ради которых
// он и заводится.
struct ServerConfig
{
    // ---- [server] ----
    // Имя инстанса: его показывают на странице входа и в десктопе после ввода
    // адреса. Пустое — клиент напишет «MeetUp».
    QString name = QStringLiteral("MeetUp");
    // Адрес, по которому сервер виден снаружи («https://meetup.linkpc.net»).
    // Нужен только для ссылок-приглашений: сам сервер за прокси своего внешнего
    // имени не знает. Пусто — клиент строит ссылку от того адреса, по которому
    // подключился сам.
    QString publicUrl;

    // ---- [web] ----
    // Раздавать ли веб-клиент. false — сервер остаётся только JSON API и
    // WebSocket-релеем: десктопные клиенты работают полностью, а страниц,
    // которые можно открыть браузером, на сервере нет вовсе.
    bool webEnabled = true;

    // ---- [log] ----
    Log::Level logLevel = Log::Level::Errors;

    // ---- Не из файла: как прошло чтение ----
    QString path;               // откуда прочитан
    bool createdNow = false;    // файла не было, создали образец
    QStringList warnings;       // непонятые ключи и значения — сказать вслух

    // Читает файл (создаёт образец, если его нет) и накладывает окружение.
    // Ошибок не возвращает: сломанный или недоступный конфиг — это повод
    // пожаловаться в warnings и работать на умолчаниях, а не повод не
    // подняться. Сервер, который не включился из-за опечатки в комментарии,
    // хуже сервера с настройками по умолчанию.
    static ServerConfig load(const QString &dataDir);

    // ---- Сведения о сборке ----
    // Приходят из -D на этапе компиляции (см. CMakeLists.txt и Dockerfile),
    // а не из файла: это свойство бинаря, а не настройка.
    //
    // Важно понимать, чем это НЕ является. Значения сообщает о себе сам
    // сервер, и тот, кто правил код, правит и эту строку. Технической защиты
    // тут быть не может: проверку выполняет тот самый бинарь, который
    // проверяют. Польза — диагностическая («у вас сборка трёхмесячной
    // давности»), и подписывать её в интерфейсе надо соответственно:
    // «сервер сообщает о себе», а не «проверено».
    static QString buildCommit();   // короткий SHA или "unknown"
    static bool buildModified();    // в рабочем дереве были правки на момент сборки
    static QString buildTime();     // ISO-8601, UTC
};
