#pragma once

#include <QString>
#include <QStringList>

#include "config/Log.h"

// Настройки сервера: файл `<data-dir>/meetup.conf` плюс переменные окружения.
//
// Зачем файл, а не только аргументы командной строки: аргументы в докере
// прибиты в CMD образа, и чтобы поменять лимит, пришлось бы править
// docker-compose.yml — то есть файл из репозитория, который затрёт следующий
// `git pull`. Конфиг лежит в `mount/` — это уже том, он переживает и
// пересборку образа, и обновление из гита.
//
// Зачем ещё и переменные окружения: тому, кто держит всё в compose, удобнее
// один раз написать `MEETUP_WEB_ENABLED=false` там, а не заходить внутрь тома.
// Окружение сильнее файла.
//
// Формат — INI: секции в квадратных скобках, `ключ = значение`, комментарии с
// `#` или `;`. Разбор свой, не QSettings, по двум причинам: QSettings считает
// значение с запятыми списком (имя сервера «Дача, второй этаж» превратилось бы
// в пустую строку) и умеет переписать файл, растеряв комментарии, ради которых
// он и заводится.
struct ServerConfig
{
    // ---- [server] ----
    // Имя инстанса: его показывают на странице входа и в десктопе после ввода
    // адреса. Пустое — клиент напишет «MeetUp».
    QString name = QStringLiteral("MeetUp");
    // Адрес, по которому сервер виден снаружи («https://meetup.linkpc.net»).
    // Нужен только для ссылок-приглашений: сам сервер за прокси своего внешнего
    // имени не знает. Пусто — клиент строит ссылку от того адреса, по которому
    // подключился сам.
    QString publicUrl;

    // ---- [web] ----
    // Раздавать ли веб-клиент. false — сервер остаётся только JSON API и
    // WebSocket-релеем: десктопные клиенты работают полностью, а страниц,
    // которые можно открыть браузером, на сервере нет вовсе.
    bool webEnabled = true;

    // ---- [auth] ----
    // Пускать ли новых людей регистрироваться. false — POST /api/auth/register
    // отвечает 403 registration_closed, а клиент вообще не рисует кнопку
    // (он узнаёт про запрет из GET /api/config).
    bool registrationOpen = true;
    // Пускать ли в комнаты без аккаунта. false вместе с закрытой регистрацией
    // даёт полностью частный сервер: войти может только тот, кого завели руками.
    bool allowAnonymousJoin = true;
    // Сколько живёт сессия входа. Продлевается, когда прошла половина срока.
    int sessionTtlDays = 30;
    // Нижняя граница длины пароля аккаунта.
    int minPasswordLen = 8;
    // Стоимость PBKDF2. Поднимать безопасно: старые хеши проверяются со своей
    // стоимостью и тихо перевариваются при следующем входе. Опускать имеет
    // смысл только на совсем слабом железе — и это ослабление, а не настройка
    // производительности.
    int pbkdf2Iters = 64000;

    // ---- [rooms] ----
    // Кто может завести разовую комнату (POST /api/rooms):
    //   open    — кто угодно, как было всегда
    //   account — только вошедшие
    //   off     — никто; на сервере работают только личные комнаты
    // Это главный вентиль против замусоривания: ручка не требовала ничего,
    // и одной командой с неё снималось несколько тысяч комнат в минуту.
    enum class RoomCreate { Open, Account, Off };
    RoomCreate anonymousCreate = RoomCreate::Open;
    // Потолок живых разовых комнат; 0 — без потолка. Личных комнат не касается:
    // их число и так ограничено числом аккаунтов, а запирать владельца снаружи
    // из-за чужого мусора — худшее, что можно сделать.
    int maxTotalRooms = 0;
    // Сколько пустая комната ждёт, прежде чем её соберёт сборщик мусора.
    // Пауза нужна, чтобы обрыв связи последнего участника не убивал комнату.
    int roomIdleTtlS = 600;
    // Сколько личных комнат человек может держать за собой. 1 — как было
    // всегда. Ограничение снимается миграцией схемы (см. SqliteDb::migrate),
    // поэтому поднять его на старой базе просто так нельзя — сервер сделает
    // это сам при первом запуске новой версии.
    int maxPersonalPerUser = 1;
    // Нижняя граница длины кода личной комнаты. На публичном сервере короткие
    // коды разбирают первыми, и трёх символов хватает на всех желающих.
    int codeMinLen = 3;
    // Ссылок-приглашений на одну комнату.
    int maxAliasesPerRoom = 5;

    // ---- [chat] ----
    // Сообщений в истории комнаты (её получает вошедший).
    int chatHistorySize = 500;
    // Картинок в истории; у более старых данные освобождаются, текст остаётся.
    // Это не украшение, а потолок памяти: замер показал 21 МБ на одну комнату,
    // набитую картинками до предела, и держатся они ещё 10 минут после ухода
    // последнего участника.
    int chatHistoryImages = 24;
    // Потолок картинки в чате, КБ (считается по сжатому изображению; в base64
    // получится примерно на треть больше).
    int chatImageMaxKb = 440;

    // ---- [log] ----
    Log::Level logLevel = Log::Level::Errors;

    // ---- Не из файла: как прошло чтение ----
    QString path;               // откуда прочитан
    bool createdNow = false;    // файла не было, создали образец
    QStringList warnings;       // непонятые ключи и значения — сказать вслух

    // Читает файл (создаёт образец, если его нет) и накладывает окружение.
    // Ошибок не возвращает: сломанный или недоступный конфиг — это повод
    // пожаловаться в warnings и работать на умолчаниях, а не повод не
    // подняться. Сервер, который не включился из-за опечатки в комментарии,
    // хуже сервера с настройками по умолчанию.
    static ServerConfig load(const QString &dataDir);

    // ---- Сведения о сборке ----
    // Приходят из -D на этапе компиляции (см. CMakeLists.txt и Dockerfile),
    // а не из файла: это свойство бинаря, а не настройка.
    //
    // Важно понимать, чем это НЕ является. Значения сообщает о себе сам
    // сервер, и тот, кто правил код, правит и эту строку. Технической защиты
    // тут быть не может: проверку выполняет тот самый бинарь, который
    // проверяют. Польза — диагностическая («у вас сборка трёхмесячной
    // давности»), и подписывать её в интерфейсе надо соответственно:
    // «сервер сообщает о себе», а не «проверено».
    static QString buildCommit();   // короткий SHA или "unknown"
    static bool buildModified();    // в рабочем дереве были правки на момент сборки
    static QString buildTime();     // ISO-8601, UTC

    // Значение rooms.anonymous_create словом — для GET /api/config.
    QString anonymousCreateName() const;

    // Потолок картинки в чате в символах base64: именно в них его считает
    // релей, а человеку в конфиге удобнее писать килобайты. base64 раздувает
    // данные на треть — отсюда 4/3.
    int chatImageMaxB64() const;
};
